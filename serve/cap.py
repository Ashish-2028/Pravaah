"""
PRAVAAH — the alerting layer: CAP 1.2 generation + WhatsApp dispatch text.

WHY CAP AT ALL
--------------
CAP (Common Alerting Protocol, OASIS 1.2) is the format IMD itself publishes
on. We already log their live feed to data/raw/live/cap/ and archived alerts
to data/raw/cap_archive/. This generator was written AFTER reading a real one
(data/raw/cap_archive/2024-06-27-07-10-22.xml) so the element order, the
`cap:` prefix, the `urn:oasis:names:tc:emergency:cap:1.2` namespace, the
+05:30 timestamps and the "lat,lon lat,lon" polygon convention all match what
an IMD reviewer expects to see. Charter rule: fetch once, inspect, then write.

THE SAFETY LAW OF THIS MODULE
-----------------------------
    status is ALWAYS "Exercise". There is no code path that emits "Actual".

This is a hackathon prototype that produces official-looking emergency
alerts. Anything indistinguishable from a real IMD bulletin would be
irresponsible, so the exercise marking is structural rather than cosmetic:

  * <cap:status>Exercise</cap:status>          — the machine-readable flag
  * <cap:note>                                 — CAP 1.2 REQUIRES a note
                                                 describing the exercise
  * identifier      urn:pravaah:exercise:...   — cannot collide with the
                                                 urn:oid:2.49.0.1.356.0.* OIDs
                                                 IMD is authorised to mint
  * sender          @pravaah-demo.invalid      — .invalid is reserved by
                                                 RFC 2606; unroutable forever
  * headline / description / instruction / areaDesc / senderName all carry a
    visible EXERCISE or DEMONSTRATION marker in the human-readable text
  * no real emergency number appears anywhere as a contact or recipient

NUMBERS
-------
Same iron rule as serve/advisory.py: every figure interpolated below comes
from the ward's own precomputed properties. This module cannot compute a
prediction and must never be given the chance to.
"""
from __future__ import annotations

from datetime import datetime, timedelta, timezone
from urllib.parse import quote
from xml.sax.saxutils import escape

CAP_NS = "urn:oasis:names:tc:emergency:cap:1.2"
IST = timezone(timedelta(hours=5, minutes=30))

SENDER = "pravaah.exercise@pravaah-demo.invalid"
SENDER_NAME = "PRAVAAH prototype (SIH 2026) — EXERCISE, not an IMD/NDMA alert"
EVENT_TYPE = "Urban Flooding"
EXERCISE_NOTE = (
    "EXERCISE / DEMONSTRATION ONLY. This message was generated by PRAVAAH, a "
    "Smart India Hackathon 2026 prototype, for demonstration purposes. It is "
    "NOT an official alert. It was not issued by the India Meteorological "
    "Department, the NDMA, the DDMA or any statutory authority, and it has "
    "not been transmitted to any public alerting channel. Take no real-world "
    "action on the basis of this message."
)
DEMO_BANNER = "*** EXERCISE — DEMONSTRATION MESSAGE — NOT A REAL ALERT ***"

# risk_band -> (urgency, severity, certainty, responseType)
BAND_CAP = {
    "critical": ("Immediate", "Extreme", "Likely", "Evacuate"),
    "high": ("Expected", "Severe", "Likely", "Prepare"),
    "watch": ("Future", "Moderate", "Possible", "Monitor"),
    "low": ("Future", "Minor", "Unlikely", "Monitor"),
}

BAND_ACTION = {
    "critical": (
        "Move people and vehicles out of low-lying pockets and basements now. "
        "Close waterlogged underpasses to traffic."
    ),
    "high": (
        "Pre-position pumps and barricades at known waterlogging points. "
        "Avoid underpasses and subways in this ward."
    ),
    "watch": (
        "Monitor drain levels and keep de-silting crews on call. "
        "No public movement restriction is indicated yet."
    ),
    "low": "Routine monitoring only. No action indicated at this probability.",
}

COMMON_ACTION = (
    "Avoid roadway underpasses, drainage ditches and low-lying areas where "
    "water collects. Stay away from power lines and electrical wires. "
    "Drive carefully."
)


# ------------------------------------------------------------- formatting
def _indian(n: float | int, digits: int = 0) -> str:
    """1234567 -> '12,34,567' (the grouping every Indian reviewer expects)."""
    if n is None:
        return "—"
    neg = n < 0
    n = abs(n)
    whole = int(n)
    frac = f"{n - whole:.{digits}f}"[1:] if digits else ""
    s = str(whole)
    if len(s) > 3:
        head, tail = s[:-3], s[-3:]
        parts = []
        while len(head) > 2:
            parts.insert(0, head[-2:])
            head = head[:-2]
        if head:
            parts.insert(0, head)
        s = ",".join(parts + [tail])
    return ("-" if neg else "") + s + frac


def _pct(v: float | None) -> int:
    return round((v or 0) * 100)


def _sent_dt(event_id: str, t: str) -> datetime:
    """
    Model clock -> a real instant. event_id is 'YYYY-MM-DD' for a replayed
    historical event, t is 'HHMM' UTC (the artefact stamp), and CAP wants
    local time with an explicit offset — IMD publishes +05:30, so we do too.

    The 'live' event carries no date in its id; today is the right day for it.
    """
    try:
        day = datetime.strptime(event_id, "%Y-%m-%d")
    except ValueError:
        day = datetime.now(timezone.utc)
    hh, mm = (int(t[:2]), int(t[2:])) if t and len(t) == 4 else (0, 0)
    utc = datetime(day.year, day.month, day.day, hh, mm, tzinfo=timezone.utc)
    return utc.astimezone(IST)


def _iso(dt: datetime | None) -> str | None:
    return dt.strftime("%Y-%m-%dT%H:%M:%S%z")[:-2] + ":" + dt.strftime("%z")[-2:] if dt else None


# ---------------------------------------------------------------- polygon
def _perp(pt, a, b) -> float:
    (x, y), (x1, y1), (x2, y2) = pt, a, b
    dx, dy = x2 - x1, y2 - y1
    if dx == 0 and dy == 0:
        return ((x - x1) ** 2 + (y - y1) ** 2) ** 0.5
    tt = ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy)
    tt = max(0.0, min(1.0, tt))
    return ((x - (x1 + tt * dx)) ** 2 + (y - (y1 + tt * dy)) ** 2) ** 0.5


def _simplify(ring: list, tol: float) -> list:
    """Ramer-Douglas-Peucker. Keeps polygon shape recognisable at low vertex counts."""
    if len(ring) < 3:
        return ring
    dmax, idx = 0.0, 0
    for i in range(1, len(ring) - 1):
        d = _perp(ring[i], ring[0], ring[-1])
        if d > dmax:
            dmax, idx = d, i
    if dmax <= tol:
        return [ring[0], ring[-1]]
    return _simplify(ring[: idx + 1], tol)[:-1] + _simplify(ring[idx:], tol)


def polygon_from_geometry(geometry: dict | None, max_points: int = 48) -> str | None:
    """
    GeoJSON [lon, lat] -> CAP "lat,lon lat,lon ... lat,lon" with a closed ring.

    CAP consumers choke on 800-vertex municipal boundaries, so we simplify to
    a readable ring. Coarsening a boundary is honest; it is the same polygon,
    drawn with fewer pen strokes.
    """
    if not geometry:
        return None
    kind, coords = geometry.get("type"), geometry.get("coordinates")
    if kind == "Polygon":
        rings = [coords[0]] if coords else []
    elif kind == "MultiPolygon":
        rings = [p[0] for p in (coords or []) if p]
    else:
        return None
    if not rings:
        return None

    ring = max(rings, key=len)  # the mainland part of a fragmented ward
    ring = [(float(p[0]), float(p[1])) for p in ring if p and len(p) >= 2]
    if len(ring) < 4:
        return None
    if ring[0] != ring[-1]:
        ring.append(ring[0])

    tol = 0.0002
    out = ring
    for _ in range(14):
        if len(out) <= max_points:
            break
        out = _simplify(ring, tol)
        tol *= 1.7
    if out[0] != out[-1]:
        out.append(out[0])
    if len(out) < 4:
        return None
    return " ".join(f"{lat:.5f},{lon:.5f}" for lon, lat in out)


# ----------------------------------------------------------------- render
def build(props: dict, geometry: dict | None, event_id: str, event_name: str, t: str) -> dict:
    """
    Ward prediction -> every field of the alert, as plain data.

    Returns the dict the preview endpoint serves and to_xml() renders. No
    figure below is computed here; each is read off `props`.
    """
    band = (props.get("risk_band") or "low").lower()
    urgency, severity, certainty, response = BAND_CAP.get(band, BAND_CAP["low"])
    name = props.get("name") or "Unknown ward"
    ward_id = str(props.get("ward_id") or "?")
    p = _pct(props.get("p_flood"))

    sent = _sent_dt(event_id, t)
    expires = sent + timedelta(hours=6)

    drivers = [d[0] for d in (props.get("drivers") or []) if d][:3]
    people = props.get("people") or 0
    hospitals = props.get("hospitals") or 0
    schools = props.get("schools") or 0
    road_km = props.get("road_km") or 0
    pumps = props.get("pumps") or 0

    sent_ist = sent.strftime("%H:%M")
    day_label = sent.strftime("%d %b %Y")

    headline = (
        f"EXERCISE — {band.upper()} urban flooding risk, {name} ward, Delhi "
        f"({p}% probability)"
    )

    # WORDING PRECISION (same rule as serve/advisory.py). `onset` and `peak`
    # are RETROSPECTIVE: the first replay frame at which this ward crossed the
    # operating point, and the frame where its probability has been highest so
    # far. They are not a predicted time-of-arrival, so this alert carries no
    # <cap:onset> element — emitting one would claim a time-to-threshold
    # forecast the models do not produce.
    timing = []
    if props.get("onset"):
        timing.append(f"flagged at this risk level since {props['onset']} IST")
    if props.get("peak") and props.get("peak") != props.get("onset"):
        timing.append(f"highest probability so far at {props['peak']} IST")
    ci = props.get("ci90")
    if isinstance(ci, (list, tuple)) and len(ci) == 2:
        timing.append(f"90% interval {ci[0]}–{ci[1]} IST")
    timing_txt = (" Timing: " + ", ".join(timing) + ".") if timing else ""

    description = (
        f"{DEMO_BANNER}\n\n"
        f"PRAVAAH's calibrated model puts the probability of surface inundation "
        f"in {name} ward (ward {ward_id}), Delhi, at {p}% for the six hours from "
        f"{sent_ist} IST on {day_label}. Risk band: {band.upper()} "
        f"(risk score {_pct(props.get('risk_score'))}%).{timing_txt}\n\n"
        f"Exposure within the ward: {_indian(people)} residents, "
        f"{_indian(hospitals)} hospitals, {_indian(schools)} schools, "
        f"{_indian(road_km, 1)} km of road, {_indian(pumps)} pumping units.\n\n"
        + (f"Leading model drivers: {', '.join(drivers)}.\n\n" if drivers else "")
        + f"Basis: precomputed probabilistic nowcast for the event "
        f"'{event_name}', model state as known at {t[:2]}:{t[2:]} UTC. No "
        f"observation issued after that moment was used.\n\n"
        f"{EXERCISE_NOTE}"
    )

    instruction = (
        f"{DEMO_BANNER}\n"
        "Take no real-world action on this message.\n\n"
        f"Actions this alert WOULD suggest if it were live: "
        f"{BAND_ACTION.get(band, BAND_ACTION['low'])} {COMMON_ACTION}\n\n"
        "In a real emergency, follow only advisories issued by IMD, NDMA or "
        "your District Disaster Management Authority."
    )

    area_desc = f"{name} ward (ward {ward_id}), Delhi NCR — EXERCISE AREA"

    return {
        "identifier": f"urn:pravaah:exercise:{event_id}:{t}:ward-{ward_id}",
        "sender": SENDER,
        "sent": _iso(sent),
        "status": "Exercise",
        "msgType": "Alert",
        "scope": "Public",
        "note": EXERCISE_NOTE,
        "language": "en-IN",
        "category": "Met",
        "event": EVENT_TYPE,
        "responseType": response,
        "urgency": urgency,
        "severity": severity,
        "certainty": certainty,
        "effective": _iso(sent),
        "expires": _iso(expires),
        "senderName": SENDER_NAME,
        "headline": headline,
        "description": description,
        "instruction": instruction,
        "areaDesc": area_desc,
        "polygon": polygon_from_geometry(geometry),
        "geocode": {"PRAVAAH_WARD_ID": ward_id},
        "parameters": {
            "PRAVAAH_p_flood": f"{props.get('p_flood')}",
            "PRAVAAH_risk_score": f"{props.get('risk_score')}",
            "PRAVAAH_risk_band": band,
            "PRAVAAH_people_exposed": str(people),
            "PRAVAAH_hospitals": str(hospitals),
            "PRAVAAH_schools": str(schools),
            "PRAVAAH_road_km": str(road_km),
            "PRAVAAH_pumps": str(pumps),
            "PRAVAAH_top_drivers": ", ".join(drivers) if drivers else "n/a",
            "PRAVAAH_flagged_since_ist": props.get("onset") or "not yet flagged",
            "PRAVAAH_peak_so_far_ist": props.get("peak") or "n/a",
            "PRAVAAH_model_clock_utc": t,
            "PRAVAAH_event": event_name,
            "EXERCISE": "TRUE — demonstration message, not an official alert",
        },
        # convenience fields for the UI, not part of CAP
        "_demo_banner": DEMO_BANNER,
        "_band": band,
        "_p_flood_pct": p,
        "_event_id": event_id,
        "_event_name": event_name,
        "_t": t,
        "_ward_id": ward_id,
        "_ward_name": name,
        "_sent_ist": sent_ist,
        "_drivers": drivers,
        "_exposure": {
            "people": people,
            "hospitals": hospitals,
            "schools": schools,
            "road_km": road_km,
            "pumps": pumps,
        },
    }


def to_xml(a: dict) -> str:
    """Render the alert dict as CAP 1.2. Element order follows the OASIS schema."""
    e = escape

    def el(tag: str, val, indent: str) -> str:
        return f"{indent}<cap:{tag}>{e(str(val))}</cap:{tag}>\n" if val not in (None, "") else ""

    x = ['<?xml version="1.0" encoding="UTF-8"?>\n']
    x.append("<!-- EXERCISE / DEMONSTRATION MESSAGE. Generated by PRAVAAH, an SIH 2026\n")
    x.append("     prototype. NOT an official IMD / NDMA / DDMA alert, and not\n")
    x.append("     transmitted to any alerting channel. status=Exercise. -->\n")
    x.append(f'<cap:alert xmlns:cap="{CAP_NS}">\n')
    for tag in ("identifier", "sender", "sent", "status", "msgType", "scope", "note"):
        x.append(el(tag, a.get(tag), "  "))
    x.append("  <cap:info>\n")
    for tag in (
        "language", "category", "event", "responseType", "urgency", "severity",
        "certainty", "effective", "expires", "senderName", "headline",
        "description", "instruction",
    ):
        x.append(el(tag, a.get(tag), "    "))
    for k, v in (a.get("parameters") or {}).items():
        x.append(
            f"    <cap:parameter>\n"
            f"      <cap:valueName>{e(k)}</cap:valueName>\n"
            f"      <cap:value>{e(str(v))}</cap:value>\n"
            f"    </cap:parameter>\n"
        )
    x.append("    <cap:area>\n")
    x.append(el("areaDesc", a.get("areaDesc"), "      "))
    x.append(el("polygon", a.get("polygon"), "      "))
    for k, v in (a.get("geocode") or {}).items():
        x.append(
            f"      <cap:geocode>\n"
            f"        <cap:valueName>{e(k)}</cap:valueName>\n"
            f"        <cap:value>{e(str(v))}</cap:value>\n"
            f"      </cap:geocode>\n"
        )
    x.append("    </cap:area>\n")
    x.append("  </cap:info>\n")
    x.append("</cap:alert>\n")
    return "".join(x)


# -------------------------------------------------------------- whatsapp
def whatsapp_text(a: dict) -> str:
    """
    The dispatch message. Short enough to read on a phone, plain text, and
    every figure is one the model already produced. Opens with the DEMO
    marker and closes with it — a forwarded screenshot of either end still
    shows that this is not real.
    """
    ex = a["_exposure"]
    drivers = ", ".join(a["_drivers"]) if a["_drivers"] else "not available"
    return (
        "PRAVAAH FLOOD ALERT (DEMO/EXERCISE)\n"
        f"Ward: {a['_ward_name']}  |  Risk: {a['_band'].upper()}\n"
        f"Flood probability: {a['_p_flood_pct']}%\n"
        f"Exposed: {_indian(ex['people'])} residents, {_indian(ex['hospitals'])} hospitals, "
        f"{_indian(ex['schools'])} schools, {_indian(ex['road_km'], 1)} km road\n"
        f"Main drivers: {drivers}\n"
        f"Issued: {a['_sent_ist']} IST  |  Event: {a['_event_name']}\n"
        "-- Generated by PRAVAAH. This is a DEMONSTRATION message."
    )


def whatsapp_url(text: str) -> str:
    """
    A wa.me deep link. NOT an API call — no account, no token, no request is
    made by this process or by the page. The presenter clicks it, WhatsApp
    opens with the message pre-composed, and a human presses send. No default
    recipient is set, and no emergency number appears anywhere in this module.
    """
    return f"https://wa.me/?text={quote(text, safe='')}"


